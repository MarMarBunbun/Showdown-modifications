    public record MoveEnumData(
            boolean implemented,
            @Nullable String game,
            @Nullable String typeOverwrite,
            @Nullable String description,
            int pp,
            int power,
            int priority,
            int accuracy,
            MoveRange moveRange,
            MoveCategory moveCategory,
            List<Type> types,
            List<String> flags
    ){
        private static MoveEnumData getMoveEnumDataFromJson(String moveName) {
            try (InputStream inputStream =
                         Move.class.getClassLoader()
                                 .getResourceAsStream("moves.json")) {

                if (inputStream == null) {
                    throw new IllegalStateException("JSON file not found");
                }

                String jsonContent = new String(
                        inputStream.readAllBytes(),
                        StandardCharsets.UTF_8
                );

                // Parse the JSON content using Gson
                Gson gson = new Gson();
                JsonObject jsonObject = gson.fromJson(jsonContent, JsonObject.class);

                if (!jsonObject.has(moveName)) throw new IllegalStateException("Move not found in JSON file: "+"\""+moveName+"\"");
                // Extract the move data using the move name as the key
                JsonObject moveData = jsonObject.getAsJsonObject(moveName);

                // Parse MoveEnumData fields from the JSON object
                boolean implemented = moveData.has("implemented") && moveData.get("implemented").getAsBoolean();
                String description = moveData.has("description") ? moveData.get("description").getAsString() : null;
                String typeOverwrite = moveData.has("typeOverwrite") ? moveData.get("typeOverwrite").getAsString() : null;
                String game = moveData.has("game") ? moveData.get("game").getAsString() : null;
                int pp = moveData.has("pp") ? moveData.get("pp").getAsInt() : 0;
                int power = moveData.has("power") ? moveData.get("power").getAsInt() : 0;
                int priority = moveData.has("priority") ? moveData.get("priority").getAsInt() : 0;
                int accuracy = moveData.has("accuracy") ? moveData.get("accuracy").getAsInt() : 0;
                MoveRange moveRange = moveData.has("moveRange") ? MoveRange.valueOf(moveData.get("moveRange").getAsString()) : MoveRange.UNKNOWN;
                MoveCategory moveCategory = moveData.has("moveCategory") ? MoveCategory.valueOf(moveData.get("moveCategory").getAsString()) : MoveCategory.UNKNOWN;
                List<Type> types = moveData.has("types") && moveData.get("types").isJsonArray()
                        ? new Gson().fromJson(moveData.getAsJsonArray("types"), new TypeToken<List<Type>>() {
                }.getType())
                        : List.of();
                List<String> flags = moveData.has("flags") && moveData.get("flags").isJsonArray()
                        ? new Gson().fromJson(moveData.getAsJsonArray("flags"), new TypeToken<List<String>>() {
                }.getType())
                        : List.of();

                return new MoveEnumData(
                        implemented,
                        game,
                        typeOverwrite,
                        description,
                        pp,
                        power,
                        priority,
                        accuracy,
                        moveRange,
                        moveCategory,
                        types,
                        flags
                );

            } catch (IOException | JsonSyntaxException e) {
                throw new IllegalStateException("Error parsing JSON file", e);
            }
        }
    }

    private MoveEnumData moveData;

    public static Move fromString(String string) {
        for (Move move : Move.values()) {
            if (move.getName().equalsIgnoreCase(string.replaceAll("_", ""))) {
                return move;
            }
        }
        return null;
    }

    public String getName() {
        var name = name();
        if (name.endsWith(getGameNamespace())) name = name.substring(0, name.length() - getGameNamespace().length());
        return name.toLowerCase().replaceAll("_", "");
    }

    public MoveEnumData getData(){
        if(moveData == null) moveData = MoveEnumData.getMoveEnumDataFromJson(this.name());
        return moveData;
    }

