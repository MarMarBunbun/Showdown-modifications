    public Map<String, Integer> getRecipeCosts() {
        var recipeCosts = new HashMap<String, Integer>();
        var power = getData().power;
        getTypes().forEach(moveType -> recipeCosts.put(moveType.type(), switch (power) {
            case 0 -> 2;
            default -> {
                if (power < 50) yield 1;
                else if (power <= 100) yield 2;
                else yield 3;
            }
        }));
        return recipeCosts;
    }


    public record MoveIdentifier(String game, String name) implements JsonSerializable {
        @Override
        public JsonElement toJson() {
            var json = new JsonObject();
            json.addProperty("game", game);
            json.addProperty("name", name);
            return json;
        }
    }

    public MoveIdentifier getIdentifier() {
        var gameNamespace = getGameNamespace();
        return new MoveIdentifier(gameNamespace, getName());
    }

